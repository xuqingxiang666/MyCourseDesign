package com.example.feature_sharecard.share

/**
 * 分享卡片插件需要的最小笔记数据。
 *
 * 【为什么不用 core 模块的 Note 实体】
 * 这是"伴生模块（plugin）"的设计要点：**对外契约只暴露自己需要的东西**。
 *
 * 如果把 `Note` 直接传进来，会带来三个问题：
 * 1. 插件与数据库实体强耦合 —— core 加一个字段，插件就得跟着改；
 * 2. 契约里出现 Room 注解类型，插件的可复用性下降；
 * 3. 插件可能拿到 `content` 密文却不知道，容易把密文画到卡片上。
 *
 * 所以由调用方（app）负责把 Note 转换成 [ShareNote]，转换时就能顺便处理
 * "加密笔记不能分享明文"这类业务规则。
 *
 * 【Java 思维对照】
 * 相当于 DTO（数据传输对象）—— 跨模块传输用的精简结构，不是数据库实体本身。
 */
data class ShareNote(
    /** 笔记 id，导出 CSV 时作为一列。 */
    val id: Long,

    /** 标题，卡片上作为主标题。 */
    val title: String,

    /**
     * 正文（**明文**）。
     *
     * 加密笔记必须由调用方在解密后传入，或者干脆不传（禁止分享加密内容）。
     * 插件自己不持有任何密钥，无法也不应该解密。
     */
    val content: String,

    /** 最后修改时间（毫秒），卡片页脚与 CSV 时间列使用。 */
    val lastModified: Long
)
